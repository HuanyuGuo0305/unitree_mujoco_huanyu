        z_dir = kp2_w - kp0_w

        x_norm = np.linalg.norm(x_dir)
        z_norm = np.linalg.norm(z_dir)
        if x_norm < 1e-8 or z_norm < 1e-8:
            return

        x_dir = x_dir / x_norm
        z_dir = z_dir / z_norm

